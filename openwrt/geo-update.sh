#!/bin/sh
# Update xray geo files from leitosama/infra "latest" release and rebuild the nft
# set inet xray direct_dst (IPv4 destinations that bypass xray, see /etc/firewall.xray).
#
# direct_dst = every IP rule in config.json that routes to "direct" and has no other
# conditions: geoip:<list> -> <list>.txt from the release, literal IP/CIDR as is,
# plus optional /etc/xray/direct-custom.txt (one IPv4/CIDR per line, # comments).
#
# xray is restarted only if geoip.dat/geosite.dat actually changed.

BASE=${GEO_BASE:-https://github.com/leitosama/infra/releases/download/latest}
CONF=/etc/xray/config.json
ASSET=/usr/share/v2ray
NFT_OUT=/etc/xray/direct4.nft
CUSTOM=/etc/xray/direct-custom.txt
WORK=/tmp/geo.new
LOCK=/tmp/geo-update.lock
SET="inet xray direct_dst"

log() { logger -t geo-update "$*"; echo "$*"; }
die() { log "ERROR: $*"; exit 1; }

mkdir "$LOCK" 2>/dev/null || { log "already running"; exit 1; }
trap 'rm -rf "$LOCK" "$WORK"' EXIT
rm -rf "$WORK" && mkdir -p "$WORK" && cd "$WORK" || die "cannot create $WORK"

fetch() {
	curl -fsSL -m 60 -o "$1" "$BASE/$1" 2>/dev/null ||
		curl -fsSL -m 60 --socks5-hostname 127.0.0.1:10808 -o "$1" "$BASE/$1" 2>/dev/null
}

# IP rules of config.json that unconditionally route to "direct"
DIRECT_IPS=$(jq -r '.routing.rules[]
	| select(.outboundTag == "direct" and .ip != null
		and ((keys - ["type", "ip", "outboundTag"]) | length) == 0)
	| .ip[]' "$CONF") || die "cannot parse $CONF"
LISTS=$(echo "$DIRECT_IPS" | sed -n 's/^geoip://p' | tr 'A-Z' 'a-z' | sort -u)

FILES="geoip.dat geosite.dat"
for l in $LISTS; do FILES="$FILES $l.txt"; done

fetch SHA256SUMS || die "download SHA256SUMS failed"
for f in $FILES; do
	grep -q "  $f\$" SHA256SUMS || die "$f is not in release SHA256SUMS (CI must publish it)"
	fetch "$f" || die "download $f failed"
done
for f in $FILES; do grep "  $f\$" SHA256SUMS; done | sha256sum -c -s - || die "sha256 mismatch"

# build nft set file
{
	for l in $LISTS; do cat "$l.txt"; done
	echo "$DIRECT_IPS" | grep -v '^geoip:'
	[ -f "$CUSTOM" ] && cat "$CUSTOM"
} | sed 's/#.*//; s/[[:space:]]//g' |
	grep -E '^[0-9]{1,3}(\.[0-9]{1,3}){3}(/[0-9]{1,2})?$' | sort -u > direct4.txt
COUNT=$(wc -l < direct4.txt)
[ -n "$LISTS" ] && [ "$COUNT" -lt 100 ] && die "only $COUNT prefixes, refusing to apply"

{
	echo "# generated by /etc/xray/geo-update.sh"
	echo "flush set $SET"
	awk -v set="$SET" '
		{ s = s (c ? ", " : "") $0; c++ }
		c == 500 { print "add element " set " { " s " }"; s = ""; c = 0 }
		END { if (c) print "add element " set " { " s " }" }' direct4.txt
} > direct4.nft

nft list set $SET > /dev/null 2>&1 || die "set $SET not loaded (firewall.xray)"
nft -c -f direct4.nft || die "nft check failed"

DAT_CHANGED=0
cmp -s geoip.dat "$ASSET/geoip.dat" && cmp -s geosite.dat "$ASSET/geosite.dat" || DAT_CHANGED=1
if [ $DAT_CHANGED = 1 ]; then
	XRAY_LOCATION_ASSET="$WORK" xray run -test -c "$CONF" > xray-test.log 2>&1 ||
		die "xray test with new geo files failed: $(tail -1 xray-test.log)"
fi

nft -f direct4.nft || die "nft apply failed"
NFT_STATE=unchanged
cmp -s direct4.nft "$NFT_OUT" || { cp direct4.nft "$NFT_OUT.tmp" && mv "$NFT_OUT.tmp" "$NFT_OUT"; NFT_STATE=updated; }

XRAY_STATE=unchanged
if [ $DAT_CHANGED = 1 ]; then
	for f in geoip.dat geosite.dat; do
		cp "$f" "$ASSET/$f.tmp" && mv "$ASSET/$f.tmp" "$ASSET/$f" || die "install $f failed"
	done
	/etc/init.d/xray restart
	XRAY_STATE="updated, xray restarted"
fi

log "direct_dst: $COUNT prefixes (lists: $(echo $LISTS), file $NFT_STATE); geo dat: $XRAY_STATE"
